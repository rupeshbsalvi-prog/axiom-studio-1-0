// PURPOSE:
//   Verify that the Explanation Engine maps the Mission state correctly
//   to the ExplanationContractV1 without any interpretation occurring in the UI.
//   This allows distinguishing between Cognition failures and Explanation failures.
// ----------------------------------------------------

import { describe, it, expect } from "vitest";
import { BRAIN_X_MISSION_INITIAL_STATE } from "../mission/MissionTypes";
import type { Mission, OutcomeDefinition, BrainXMissionStateData } from "../mission/MissionTypes";
import {
  createMission,
  transitionMissionStatus,
  addObjective,
  addDecision,
  resolveDecision,
} from "../mission/MissionService";
import { addNode, addEdge } from "../mission/ReasoningGraphEngine";
import { createDelegation } from "../mission/DelegationEngine";
import { deriveExplanation } from "../mission/ExplanationEngine";
import { deriveTelemetrySnapshotV1 } from "../mission/TelemetryEngineV1";

const TEST_OUTCOME: OutcomeDefinition = {
  successCriteria: ["criteria-1"],
  acceptanceCriteria: ["acceptance-1"],
  completionCondition: "completed-condition",
};

function emptyState(): BrainXMissionStateData {
  return { ...BRAIN_X_MISSION_INITIAL_STATE };
}

describe("EVR1 — Explanation Correctness Validation", () => {
  it("derives correct timeline, reasoning graph, and predictability properties for a Created Mission", () => {
    const { state, mission } = createMission(emptyState(), "Develop a new auth module", TEST_OUTCOME);
    const contract = deriveExplanation(mission, []);

    // Verify Invariants
    expect(contract.missionId).toBe(mission.id);
    expect(contract.title).toBe(mission.title);
    expect(contract.intent).toBe("Develop a new auth module");
    expect(contract.status).toBe("created");

    // Timeline derivation
    expect(contract.timeline.currentStage).toBe("Created");
    expect(contract.timeline.completedStages).toEqual([]);
    expect(contract.timeline.pendingStages).toEqual(["Planning", "Executing", "Verifying", "Completed"]);
    expect(contract.timeline.durationMs).toBeGreaterThanOrEqual(0);

    // Predictability derivation
    expect(contract.predictability.predictedNextAction).toContain("Transition to Planning");
    expect(contract.predictability.confidence).toBe(0.95);
    expect(contract.predictability.rationale).toBeDefined();

    // No active decision
    expect(contract.activeDecision).toBeUndefined();
  });

  it("derives correct reasoning graph, critical path, and predictability properties for a Planning Mission", () => {
    let { state, mission } = createMission(emptyState(), "Decompose intent", TEST_OUTCOME);
    state = transitionMissionStatus(state, mission.id, "planning");
    
    // Add objectives
    const res1 = addObjective(state, mission.id, "Deconstruct goals", ["brief"]);
    state = res1.state;
    const obj1Id = res1.objectiveId;

    const res2 = addObjective(state, mission.id, "Establish edges", ["graph"]);
    state = res2.state;
    const obj2Id = res2.objectiveId;

    // Retrieve updated mission from state
    mission = state.missions.find((m) => m.id === mission.id)!;
    
    // Construct reasoning graph
    mission.reasoningGraph = addNode(mission.reasoningGraph, obj1Id, "task", "Initial node");
    mission.reasoningGraph = addNode(mission.reasoningGraph, obj2Id, "task", "Second node");
    
    // Retrieve the node IDs generated by addNode
    const node1 = mission.reasoningGraph.nodes.find((n) => n.objectiveId === obj1Id)!;
    const node2 = mission.reasoningGraph.nodes.find((n) => n.objectiveId === obj2Id)!;
    
    mission.reasoningGraph = addEdge(mission.reasoningGraph, node1.id, node2.id, "depends-on", "Must sort first");

    const contract = deriveExplanation(mission, []);

    // Reasoning graph assertions
    expect(contract.reasoningGraph.nodes.length).toBe(2);
    expect(contract.reasoningGraph.nodes[0].label).toBe(`TASK: Deconstruct goals`);
    expect(contract.reasoningGraph.nodes[0].rationale).toBe("Initial node");
    expect(contract.reasoningGraph.edges.length).toBe(1);
    expect(contract.reasoningGraph.edges[0].relationship).toBe("depends-on");
    expect(contract.reasoningGraph.edges[0].rationale).toBe("Must sort first");

    // Critical Path
    expect(contract.reasoningGraph.criticalPathNodeIds).toEqual([node1.id, node2.id]);

    // Predictability
    expect(contract.predictability.predictedNextAction).toContain("Construct Reasoning Graph");
    expect(contract.predictability.confidence).toBe(0.90);
  });

  it("derives active decision details when mission is Paused", () => {
    let { state, mission } = createMission(emptyState(), "Test decision flow", TEST_OUTCOME);
    state = transitionMissionStatus(state, mission.id, "planning");
    
    const res = addObjective(state, mission.id, "Goal A", ["A"]);
    state = res.state;
    const objId = res.objectiveId;
    
    const resDec = addDecision(
      state,
      mission.id,
      objId,
      "Should we use OAuth or SAML?",
      ["OAuth", "SAML"],
      "OAuth",
      0.85,
      "OAuth is easier to configure"
    );
    state = resDec.state;
    
    // Note: addDecision automatically transitions the mission to "paused", 
    // so calling transitionMissionStatus is not needed and would be invalid.

    // Retrieve updated mission
    mission = state.missions.find((m) => m.id === mission.id)!;

    const contract = deriveExplanation(mission, []);

    // Verify Decision
    expect(contract.activeDecision).toBeDefined();
    expect(contract.activeDecision?.question).toBe("Should we use OAuth or SAML?");
    expect(contract.activeDecision?.recommendation).toBe("OAuth");
    expect(contract.activeDecision?.confidence).toBe(0.85);
    expect(contract.activeDecision?.rationale).toBe("OAuth is easier to configure");

    // Predictability shows pending user choice
    expect(contract.predictability.predictedNextAction).toContain("User resolution");
    expect(contract.predictability.confidence).toBe(1.0);
  });

  it("derives delegation monitor details during active execution", () => {
    let { state, mission } = createMission(emptyState(), "Test delegation state", TEST_OUTCOME);
    state = transitionMissionStatus(state, mission.id, "planning");
    
    const res = addObjective(state, mission.id, "Implement feature", ["code"]);
    state = res.state;
    const objId = res.objectiveId;
    
    const resDel = createDelegation(
      state,
      mission.id,
      objId,
      "axiomAi",
      { file: "index.js" },
      { schema: "JSON", validationRules: ["has-export"] }
    );
    state = resDel.state;
    
    state = transitionMissionStatus(state, mission.id, "active");

    // Retrieve updated mission
    mission = state.missions.find((m) => m.id === mission.id)!;

    const contract = deriveExplanation(mission, []);

    // Verify Delegation
    expect(contract.delegations.length).toBe(1);
    expect(contract.delegations[0].targetStudio).toBe("axiomAi");
    expect(contract.delegations[0].status).toBe("sent");
    expect(contract.delegations[0].progressPercent).toBe(25);
    expect(contract.delegations[0].payloadSummary).toContain("index.js");

    // Predictability shows waiting for delegation
    expect(contract.predictability.predictedNextAction).toContain("Await result validation");
    expect(contract.predictability.confidence).toBe(0.85);
  });

  describe("TelemetryEngineV1 — Cognitive UX Metrics", () => {
    it("calculates optimal telemetry metrics for a newly Created Mission", () => {
      const { state, mission } = createMission(emptyState(), "Clean code clean architecture", TEST_OUTCOME);
      const explanation = deriveExplanation(mission, []);
      const snapshot = deriveTelemetrySnapshotV1({
        activeMission: mission,
        missions: [mission],
        explanation,
        timestamp: 1000,
      });

      expect(snapshot.productMetrics.cts).toBe(95);
      expect(snapshot.productMetrics.cls).toBe(0);
      expect(snapshot.productMetrics.mcs).toBe(96); // 96 due to JavaScript floating-point precision: (0.7 * 0.95 + 0.3 * 1.0) * 100 = 96.4999... -> Math.round = 96
      expect(snapshot.productMetrics.ees).toBe(100);
      expect(snapshot.derivedState.healthState).toBe("optimal");
      expect(snapshot.derivedState.cognitiveLoadLevel).toBe("low");
      expect(snapshot.timestamp).toBe(1000);
    });

    it("calculates attention or critical healthState under high load or low consistency", () => {
      let { state, mission } = createMission(emptyState(), "Stress test telemetry", TEST_OUTCOME);
      state = transitionMissionStatus(state, mission.id, "planning");

      const objIds: string[] = [];
      // Add 10 pending objectives to increase CLS
      for (let i = 0; i < 10; i++) {
        const res = addObjective(state, mission.id, `Obj ${i}`, [`out ${i}`]);
        state = res.state;
        objIds.push(res.objectiveId);
      }

      // Retrieve updated mission
      mission = state.missions.find((m) => m.id === mission.id)!;

      // Update reasoning graph nodes
      for (let i = 0; i < 10; i++) {
        mission.reasoningGraph = addNode(mission.reasoningGraph, objIds[i], "task", "Pending task node");
      }

      // Add active decision (this automatically sets status to "paused")
      const resDec = addDecision(
        state,
        mission.id,
        objIds[0],
        "Scale now?",
        ["yes", "no"],
        "yes",
        0.8,
        "rationale"
      );
      state = resDec.state;

      // Retrieve final updated mission
      mission = state.missions.find((m) => m.id === mission.id)!;

      const explanation = deriveExplanation(mission, []);
      const snapshot = deriveTelemetrySnapshotV1({
        activeMission: mission,
        missions: [mission],
        explanation,
        timestamp: 2000,
      });

      // pendingCount = 10 (* 5 = 50)
      // activeDecision load = 35
      // CLS = 50 + 35 = 85 (triggers critical!)
      expect(snapshot.productMetrics.cls).toBe(85);
      expect(snapshot.derivedState.healthState).toBe("critical");
      expect(snapshot.derivedState.cognitiveLoadLevel).toBe("high");
    });

    it("verifies telemetry engine returns deterministic snapshots for identical inputs", () => {
      const { state, mission } = createMission(emptyState(), "Deterministic test", TEST_OUTCOME);
      const explanation = deriveExplanation(mission, []);
      const context1 = {
        activeMission: mission,
        missions: [mission],
        explanation,
        timestamp: 5000,
      };
      const context2 = {
        activeMission: mission,
        missions: [mission],
        explanation,
        timestamp: 5000,
      };

      const snapshot1 = deriveTelemetrySnapshotV1(context1);
      const snapshot2 = deriveTelemetrySnapshotV1(context2);

      expect(snapshot1).toEqual(snapshot2);
      expect(snapshot1.productMetrics.cts).toBe(snapshot2.productMetrics.cts);
      expect(snapshot1.derivedState.healthState).toBe(snapshot2.derivedState.healthState);
    });
  });
});
